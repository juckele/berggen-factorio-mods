def _tank(rng, mat):
    h, r = rng.uniform(0.3, 0.5), rng.uniform(0.1, 0.15)
    prof = [(0, 0), (r, 0), (r, h), (r * 0.8, h + r * 0.35), (r * 0.35, h + r * 0.5), (0, h + r * 0.5)]
    p = [lathe(prof, (0, 0, 0), mat, seg=28)]
    for k in range(2):
        p.append(tor(r * 1.01, 0.015, (0, h * (0.25 + 0.5 * k), 0), M["iron"], rot=(90, 0, 0), seg=28, sides=6))
    return p, h + r * 0.5


def _crate(rng, mat):
    s = rng.uniform(0.16, 0.26)
