# ----------------------------------------------------------------- materials
TIER_ARMOUR = {1: "#7b7f6a", 2: "#3e6ea8", 3: "#8a9f40"}  # A/B concepts: grey-olive, blue, lime
TIER_ARMOUR_DARK = {1: "#5a5d4e", 2: "#2c4f7c", 3: "#677f2a"}
# Paint colours for C/D: tier 1 is tried in the inserter/belt family.
PAINT = {"yellow": "#d8a72c", "orange": "#d27a2c", "red": "#b3413a", "blue": "#3e6ea8", "lime": "#8a9f40", "olive": "#7b7f6a"}
TIER_PAINT = {1: "orange", 2: "blue", 3: "lime"}


def darker(hexcol, f=0.72):
    h = hexcol.lstrip("#")
    return "#" + "".join(f"{int(int(h[i:i + 2], 16) * f):02x}" for i in (0, 2, 4))


def paint_mat(colour, dark=False):
    c = PAINT.get(colour, colour)
    return {"color": darker(c) if dark else c, "roughness": 0.5, "specular": 0.35}

M = {
    "iron": {"color": "#4b4744", "roughness": 0.55, "specular": 0.35},
    "iron_dark": {"color": "#2f2c2a", "roughness": 0.6, "specular": 0.3},
    "steel": {"color": "#9a9a98", "roughness": 0.3, "specular": 0.7},
    "brass": {"color": "#a08550", "roughness": 0.35, "specular": 0.65},
    "copper": {"color": "#a65f37", "roughness": 0.4, "specular": 0.55},
    "rust": {"color": "#6e5442", "roughness": 0.75, "specular": 0.15},
    "rubber": {"color": "#2a2726", "roughness": 0.8, "specular": 0.1},
    "glass": {"color": "#e8d27a", "roughness": 0.15, "specular": 0.9},
}


def armour(tier, dark=False):
    return {"color": (TIER_ARMOUR_DARK if dark else TIER_ARMOUR)[tier], "roughness": 0.5, "specular": 0.35}


# ----------------------------------------------------------------- part helpers
def box(size, pos, mat, rot=(0, 0, 0), tag=None):
    p = {"shape": "box", "size": [round(v, 4) for v in size], "position": [round(v, 4) for v in pos], "rotation": list(rot), "material": mat}
    if tag:
        p["tag"] = tag
    return p


def cyl(r, h, pos, mat, rot=(0, 0, 0), seg=48, tag=None):
    """Cylinder centred on `pos`, axis along local y (the DSL's own cylinder starts at its base)."""
    p = {"shape": "lathe", "profile": [[0, -h / 2], [r, -h / 2], [r, h / 2], [0, h / 2]], "segments": seg,
         "position": [round(v, 4) for v in pos], "rotation": list(rot), "material": mat}
    if tag:
        p["tag"] = tag
    return p


def sph(r, pos, mat, seg=16):
    return {"shape": "sphere", "radius": r, "segments": seg, "rings": max(6, seg // 2), "position": [round(v, 4) for v in pos], "material": mat}


def tor(major, minor, pos, mat, rot=(0, 0, 0), arc=360.0, seg=48, sides=12):
    return {"shape": "torus", "major": major, "minor": minor, "arc": arc, "segments": seg, "sides": sides,
            "position": [round(v, 4) for v in pos], "rotation": list(rot), "material": mat}


def lathe(profile, pos, mat, rot=(0, 0, 0), seg=48):
    return {"shape": "lathe", "profile": [[round(a, 4), round(b, 4)] for a, b in profile], "segments": seg,
            "position": [round(v, 4) for v in pos], "rotation": list(rot), "material": mat}


def obj(name, parts, pos=(0, 0, 0), rot=(0, 0, 0)):
    return {"name": name, "position": [round(v, 4) for v in pos], "rotation": [round(v, 3) for v in rot], "parts": parts}


def rivets_line(a, b, n, mat, r=0.022, normal_off=(0, 0, 0)):
    out = []
    for i in range(n):
        t = (i + 0.5) / n
        out.append(sph(r, [a[k] + (b[k] - a[k]) * t + normal_off[k] for k in range(3)], mat, seg=10))
    return out


# ----------------------------------------------------------------- local-frame components
# Components are built in their own frame and placed with an object transform,
# so a moving part (gear, wheel, crank) is posed by changing one rotation.


def gear_parts(radius, teeth, thick, mat, hub_mat, spokes=0, bore=True, rim=0.22, tooth_w=0.5):
    """Gear in the local XY plane, axle along local z, centred at the origin.
    spokes: a spoked wheel with a rim `rim` x radius deep; tooth_w: tooth width as a fraction of the pitch."""
    parts = []
    rim_w = radius * (rim if spokes else 1.0)
    if spokes:
        # a flat rim band (a gear's rim, not a round wheel's tyre)
        parts.append(lathe([(radius - rim_w, -thick / 2), (radius, -thick / 2), (radius, thick / 2), (radius - rim_w, thick / 2)], (0, 0, 0), mat, rot=(90, 0, 0), seg=64))
        for i in range(spokes):
            a = 360.0 * i / spokes
            parts.append(box((radius * 0.2, radius * 0.86, thick * 0.7), (0.43 * radius * math.cos(math.radians(a + 90)), 0.43 * radius * math.sin(math.radians(a + 90)), 0), mat, rot=(0, 0, a)))
    else:
        parts.append(cyl(radius, thick, (0, 0, 0), mat, rot=(90, 0, 0), seg=64))
        parts.append(cyl(radius * 0.72, thick * 1.15, (0, 0, 0), mat, rot=(90, 0, 0), seg=48))  # raised web ring
    tw = 2 * math.pi * radius / max(teeth, 1) * tooth_w
    th = radius * (0.22 if teeth <= 18 else 0.16)  # chunky teeth read at sprite size
    for i in range(teeth):
        a = 360.0 * i / teeth
        ar = math.radians(a)
        parts.append(box((tw, th, thick), ((radius + th * 0.35) * math.cos(ar), (radius + th * 0.35) * math.sin(ar), 0), mat, rot=(0, 0, a - 90)))
    parts.append(cyl(radius * 0.26, thick * 1.5, (0, 0, 0), hub_mat, rot=(90, 0, 0), seg=32))
    if bore:
        parts.append(cyl(radius * 0.1, thick * 1.7, (0, 0, 0), M["iron_dark"], rot=(90, 0, 0), seg=16))
    return parts


def handwheel_parts(radius, mat, hub_mat, spokes=4, rim=0.11, spoke=0.07):
    """Valve handwheel in local XY plane (axle along z). rim/spoke: thicknesses as fractions of the radius."""
    parts = [tor(radius, radius * rim, (0, 0, 0), mat, seg=48, sides=10)]
    for i in range(spokes):
        a = 360.0 * i / spokes + 45
        ar = math.radians(a)
        parts.append(cyl(radius * spoke, radius, (0.5 * radius * math.cos(ar), 0.5 * radius * math.sin(ar), 0), mat, rot=(0, 0, a - 90), seg=12))
    parts.append(cyl(radius * (0.22 + spoke), radius * 0.25, (0, 0, 0), hub_mat, rot=(90, 0, 0), seg=24))
    return parts


def chain_parts(a, b, sprocket_r, mat, link=0.07):
    """Chain loop between two sprocket centres in the local XY plane."""
    ax, ay = a
    bx, by = b
    L = math.hypot(bx - ax, by - ay)
    ang = math.degrees(math.atan2(by - ay, bx - ax))
    ux, uy = (bx - ax) / L, (by - ay) / L
    nx, ny = -uy, ux
    parts = []
    n = max(2, int(L / link))
    for side in (1, -1):
        for i in range(n):
            t = (i + 0.5) / n
            cx = ax + (bx - ax) * t + nx * sprocket_r * side
            cy = ay + (by - ay) * t + ny * sprocket_r * side
            parts.append(box((link * 0.85, link * 0.42, 0.05), (cx, cy, 0), mat, rot=(0, 0, ang)))
    return parts


# ----------------------------------------------------------------- the shared tub
FOOT = 1.42  # half-size of the machine footprint (tiles)
CH = 0.42  # chamfer of the front corners


def plinth(tier):
    """Dark base slab, chamfered at the front, with a lip of plates."""
    parts = []
    h = 0.14
    # main slab: centre box + two angled corner boxes (front chamfers)
    parts.append(box((2 * FOOT, h, 2 * FOOT - CH), (0, h / 2, -CH / 2), M["iron_dark"]))
    parts.append(box((2 * FOOT - 2 * CH, h, CH), (0, h / 2, FOOT - CH / 2), M["iron_dark"]))
    d = CH * math.sqrt(2)
    for sx in (-1, 1):
        parts.append(box((d, h, d * 0.5), (sx * (FOOT - CH / 2) - sx * 0.04, h / 2, FOOT - CH / 2 - 0.04), M["iron_dark"], rot=(0, sx * 45, 0)))
    # foot blocks along the front edge (vanilla has a row of dark blocks under the front)
    for i in range(6):
        x = -0.95 + i * 0.38
        parts.append(box((0.3, 0.1, 0.12), (x, 0.05, FOOT + 0.02), M["iron"]))
    return parts


def wall_plate(w, h, t, mat, rivet_mat, n_rivets=(3, 2)):
    """A riveted plate in the local XY plane, facing +z; origin at bottom centre."""
    parts = [box((w, h, t), (0, h / 2, 0), mat)]
    parts.append(box((w * 0.86, h * 0.8, t * 0.4), (0, h / 2, t * 0.6), mat))  # raised panel
    nx, ny = n_rivets
    for i in range(nx):
        x = -w * 0.42 + i * (w * 0.84 / max(nx - 1, 1))
        for y in (h * 0.08, h * 0.92):
            parts.append(sph(0.024, (x, y, t * 0.55), rivet_mat, seg=10))
    for j in range(1, ny):
        y = h * j / ny
        for x in (-w * 0.45, w * 0.45):
            parts.append(sph(0.024, (x, y, t * 0.55), rivet_mat, seg=10))
    return parts


def tub(tier, wall_h=0.86, front_h=0.6, rake=22):
    """Open-topped armoured tub. Returns objects."""
    A, Ad = armour(tier), armour(tier, dark=True)
    objs = [obj("plinth", plinth(tier))]
    base = 0.14
    t = 0.12
    # back wall: three plates
    for i in range(3):
        x = -0.94 + i * 0.94
        objs.append(obj(f"wall_back_{i}", wall_plate(0.92, wall_h, t, A, M["steel"]), pos=(x, base, -FOOT + t / 2), rot=(0, 180, 0)))
    # side walls: from back corner to the chamfer
    side_len = 2 * FOOT - CH
    for sx, nm in ((-1, "left"), (1, "right")):
        n = 3
        seg = side_len / n
        for i in range(n):
            z = -FOOT + seg * (i + 0.5)
            objs.append(obj(f"wall_{nm}_{i}", wall_plate(seg * 0.98, wall_h, t, A, M["steel"], (2, 2)), pos=(sx * (FOOT - t / 2), base, z), rot=(0, sx * 90, 0)))
        # chamfer wall (angled, slightly lower)
        d = CH * math.sqrt(2)
        objs.append(obj(f"wall_{nm}_chamfer", wall_plate(d * 0.96, wall_h * 0.92, t, Ad, M["steel"], (2, 2)),
                        pos=(sx * (FOOT - CH / 2 - 0.03), base, FOOT - CH / 2 - 0.03), rot=(0, sx * 45, 0)))
        # corner post / ladder brace at the front chamfer (vanilla: angled strut with rungs)
        bh = front_h + 0.12
        brace = [box((0.1, bh, 0.1), (-0.08, bh / 2, 0), M["iron"]), box((0.1, bh, 0.1), (0.08, bh / 2, 0), M["iron"]),
                 box((0.26, 0.08, 0.12), (0, bh, 0), M["iron"])]
        for k in range(3):
            brace.append(box((0.2, 0.04, 0.06), (0, 0.15 + k * 0.17, 0.02), M["steel"]))
        objs.append(obj(f"brace_{nm}", brace, pos=(sx * (FOOT - CH - 0.05), base, FOOT - 0.02), rot=(-rake, sx * 25, 0)))
    # raked front wall: four riveted panels leaning back
    fw = 2 * FOOT - 2 * CH - 0.12
    for i in range(4):
        x = -fw / 2 + fw / 8 + i * fw / 4
        objs.append(obj(f"wall_front_{i}", wall_plate(fw / 4 * 0.96, front_h, t, A, M["steel"], (2, 2)), pos=(x, base, FOOT - 0.06), rot=(-rake, 0, 0)))
    # rim along the top of the walls (iron capping)
    cap = []
    cap.append(box((2 * FOOT, 0.06, 0.16), (0, base + wall_h + 0.03, -FOOT + 0.08), M["iron"]))
    for sx in (-1, 1):
        cap.append(box((0.16, 0.06, 2 * FOOT - CH), (sx * (FOOT - 0.08), base + wall_h + 0.03, -CH / 2), M["iron"]))
    objs.append(obj("rim", cap))
    # interior floor (dark), so gaps between machinery read as depth
    objs.append(obj("floor", [box((2 * FOOT - 0.25, 0.04, 2 * FOOT - 0.3), (0, base + 0.22, -0.05), M["iron_dark"])]))
    return objs


# ----------------------------------------------------------------- the tapered tub (C, D)
LEAN = 16  # degrees the walls lean inward: their outer faces show from above, like vanilla


def tub_tapered(colour, wall_h=0.86, front_h=0.6, rake=24, foot=1.4):
    """Armoured tub whose walls all lean in (a truncated pyramid), slanted corner panels."""
    A, Ad = paint_mat(colour), paint_mat(colour, dark=True)
    objs = []
    base, t = 0.14, 0.12
    sL, cL = math.sin(math.radians(LEAN)), math.cos(math.radians(LEAN))
    inset = wall_h * sL
    top = base + wall_h * cL
    # plinth, a little wider than the walls' feet
    pl = [box((2 * foot + 0.06, 0.14, 2 * foot - CH), (0, 0.07, -CH / 2), M["iron_dark"]),
          box((2 * foot - 2 * CH, 0.14, CH + 0.03), (0, 0.07, foot - CH / 2 + 0.015), M["iron_dark"])]
    d = CH * math.sqrt(2)
    for sx in (-1, 1):
        pl.append(box((d + 0.06, 0.14, d * 0.5), (sx * (foot - CH / 2) - sx * 0.03, 0.07, foot - CH / 2 - 0.03), M["iron_dark"], rot=(0, sx * 45, 0)))
    for i in range(6):
        pl.append(box((0.3, 0.1, 0.12), (-0.95 + i * 0.38, 0.05, foot + 0.04), M["iron"]))
    objs.append(obj("plinth", pl))
    # back wall: three leaning plates (slightly wider so the corners overlap)
    for i in range(3):
        objs.append(obj(f"wall_back_{i}", wall_plate(0.94 if i == 1 else 0.86, wall_h, t, A, M["steel"]), pos=((-0.9 + i * 0.9), base, -foot + t / 2), rot=(-LEAN, 180, 0)))
    side_len = 2 * foot - CH
    for sx, nm in ((-1, "left"), (1, "right")):
        seg = side_len / 3
        for i in range(3):
            z = -foot + seg * (i + 0.5)
            w_ = seg * (0.9 if i == 0 else 1.0)
            objs.append(obj(f"wall_{nm}_{i}", wall_plate(w_, wall_h, t, A, M["steel"], (2, 2)), pos=(sx * (foot - t / 2), base, z + (seg - w_) / 2), rot=(-LEAN, sx * 90, 0)))
        # back corner post along the line where the two leaning walls meet (covers the plates' corners)
        p0 = (sx * foot, base, -foot)
        p1 = (sx * (foot - inset), top + 0.04, -foot + inset)
        v = [p1[i] - p0[i] for i in range(3)]
        ln = math.sqrt(sum(c * c for c in v))
        ax_ = math.degrees(math.asin(v[2] / ln))
        bz = math.degrees(math.atan2(-v[0], v[1]))
        objs.append(obj(f"post_{nm}", [box((0.17, ln, 0.17), (0, 0, 0), M["iron"]), box((0.21, 0.06, 0.21), (0, ln / 2 - 0.03, 0), M["iron_dark"])],
                        pos=tuple((p0[i] + p1[i]) / 2 - (0.04 * sx if i == 0 else 0) + (0.04 if i == 2 else 0) for i in range(3)), rot=(ax_, 0, bz)))
        # slanted chamfer panel at the front corner, leaning like the rest
        objs.append(obj(f"wall_{nm}_chamfer", wall_plate(d * 1.02, wall_h * 0.9, t, Ad, M["steel"], (2, 2)),
                        pos=(sx * (foot - CH / 2 - 0.03), base, foot - CH / 2 - 0.03), rot=(-LEAN - 6, sx * 45, 0)))
        # ladder brace at the front corner (vanilla's angled strut with rungs)
        bh = front_h + 0.12
        brace = [box((0.1, bh, 0.1), (-0.08, bh / 2, 0), M["iron"]), box((0.1, bh, 0.1), (0.08, bh / 2, 0), M["iron"]), box((0.26, 0.08, 0.12), (0, bh, 0), M["iron"])]
        for k in range(3):
            brace.append(box((0.2, 0.04, 0.06), (0, 0.15 + k * 0.17, 0.02), M["steel"]))
        objs.append(obj(f"brace_{nm}", brace, pos=(sx * (foot - CH - 0.05), base, foot - 0.02), rot=(-rake, sx * 25, 0)))
    fw = 2 * foot - 2 * CH - 0.12
    for i in range(4):
        x = -fw / 2 + fw / 8 + i * fw / 4
        objs.append(obj(f"wall_front_{i}", wall_plate(fw / 4 * 0.96, front_h, t, A, M["steel"], (2, 2)), pos=(x, base, foot - 0.06), rot=(-rake, 0, 0)))
    # iron capping along the leaning walls' tops
    xi = foot - t / 2 - inset
    zb = -foot + t / 2 + inset
    cap = [box((2 * xi + 0.14, 0.06, 0.16), (0, top + 0.03, zb), M["iron"])]
    for sx in (-1, 1):
        cap.append(box((0.16, 0.06, (foot - CH) - zb + 0.05), (sx * xi, top + 0.03, (zb + foot - CH) / 2), M["iron"]))
    objs.append(obj("rim", cap))
    objs.append(obj("floor", [box((2 * xi, 0.04, foot - CH - zb + CH * 0.8), (0, base + 0.22, (zb + foot - CH * 0.2) / 2), M["iron_dark"])]))
    return objs, {"top": top, "xi": xi, "zb": zb, "zf": foot - 0.06 - front_h * math.sin(math.radians(rake)), "front_top": base + front_h * math.cos(math.radians(rake))}


# ----------------------------------------------------------------- moving machinery
GEAR_AXIS_YAW = 38  # gear planes face front-left; the shaft runs back-right
# Animation loops: in one cycle (phase 0 -> 1) every gear advances this many
# teeth, so the last frame meets the first; meshed gears turn in opposite senses.
TEETH_PER_CYCLE = 2


def spin(phase, teeth, sense=1):
    return (sense * phase * 360.0 * TEETH_PER_CYCLE / teeth) % 360


def spun(parts, ang):
    """Turn parts built round their local z axis (an axle) by `ang` degrees,
    inside the object's frame. (An object's own rotation applies z last, i.e.
    about the world z axis, so spinning there would wobble a tilted wheel.)"""
    if not ang:
        return parts
    c, s = math.cos(math.radians(ang)), math.sin(math.radians(ang))
    out = []
    for p in parts:
        q = dict(p)
        x, y, z = q["position"]
        q["position"] = [round(c * x - s * y, 5), round(s * x + c * y, 5), z]
        rx, ry, rz = q.get("rotation", [0, 0, 0])
        q["rotation"] = [rx, ry, rz + ang]  # rotations are Rz·Ry·Rx, so this is Rz(ang) applied after the part's own
        out.append(q)
    return out


def gear_stack(tier, phase, centre=(-0.72, 0.62, 0.62), radius=0.5, label="gear"):
    """1-3 big upright gears at the front-left on one shaft (vanilla placement)."""
    objs = []
    n = tier
    yaw = GEAR_AXIS_YAW
    ax = (math.sin(math.radians(yaw)) * -1, 0, math.cos(math.radians(yaw)) * -1)  # shaft direction: toward back-right
    ax = (-ax[0], 0, ax[2])
    spacing = 0.2
    for i in range(n):
        r = radius * (1 - 0.1 * i)
        c = (centre[0] + ax[0] * spacing * i, centre[1] + 0.02 * i, centre[2] + ax[2] * spacing * i)
        teeth = 16  # one shaft: all turn together, so they share a tooth count to loop
        ang = spin(phase, teeth)
        objs.append(obj(f"{label}_{i}", spun(gear_parts(r, teeth, 0.09, M["steel"] if i == 0 else M["brass"], M["brass"] if i == 0 else M["steel"]), ang),
                        pos=c, rot=(0, -yaw, 0)))
    # shaft and bearing block
    L = spacing * (n - 1) + 0.45
    sc = (centre[0] + ax[0] * L / 2 - ax[0] * 0.15, centre[1], centre[2] + ax[2] * L / 2 - ax[2] * 0.15)
    objs.append(obj(f"{label}_shaft", [cyl(0.05, L, (0, 0, 0), M["steel"], rot=(90, 0, 0), seg=16)], pos=sc, rot=(0, -yaw, 0)))
    bc = (centre[0] + ax[0] * (L - 0.1), 0.38, centre[2] + ax[2] * (L - 0.1))
    objs.append(obj(f"{label}_bearing", [box((0.22, 0.34, 0.2), (0, 0, 0), M["iron"]), cyl(0.09, 0.24, (0, 0.17, 0), M["iron"], rot=(90, 0, 0), seg=24)], pos=bc, rot=(0, -yaw, 0)))
    return objs


def handwheel(tier, phase, pos=(-0.98, 0.95, -0.15)):
    return [obj("handwheel", spun(handwheel_parts(0.24, M["steel"], M["brass"]), phase * 90), pos=pos, rot=(-40, -20, 0)),
            obj("handwheel_valve", [cyl(0.07, 0.28, (0, 0, 0), M["brass"], rot=(0, 0, 90), seg=16), box((0.18, 0.2, 0.18), (0.18, 0, 0), M["copper"])],
                pos=(pos[0] - 0.05, pos[1] - 0.12, pos[2] - 0.12), rot=(-40, -20, 0))]


def crank(tier, phase, pivot=(-0.95, 1.02, -1.08)):
    """Lever arm at the back-left: pivot pulley on the back wall, arm swinging down-right."""
    swing = 18 * math.sin(phase * 2 * math.pi)
    arm_len = 0.95
    parts = [cyl(0.14, 0.1, (0, 0, 0), M["steel"], rot=(90, 0, 0), seg=32),
             cyl(0.05, 0.16, (0, 0, 0), M["brass"], rot=(90, 0, 0), seg=16),
             box((arm_len, 0.11, 0.07), (arm_len / 2, 0, 0.06), M["steel"]),
             cyl(0.08, 0.12, (arm_len, 0, 0.06), M["iron"], rot=(90, 0, 0), seg=24)]
    return [obj("crank_arm", spun(parts, swing), pos=pivot, rot=(-50, 0, -28)),
            obj("crank_mount", [box((0.3, 0.3, 0.14), (0, 0, 0), M["iron"])], pos=(pivot[0], pivot[1] - 0.15, pivot[2] - 0.05))]


def chain_drive(tier, phase, a=(0.0, 0.95, -0.62), b=(1.05, 0.95, -0.98)):
    """Chain running across the top-right between two sprockets (tiers 2-3)."""
    dx, dz = b[0] - a[0], b[2] - a[2]
    L = math.hypot(dx, dz)
    yaw = math.degrees(math.atan2(-dz, dx))
    pitch = L / max(2, int(L / 0.07))
    shift = (phase * TEETH_PER_CYCLE * pitch) % pitch
    parts = chain_parts((0 + shift, 0), (L + shift, 0), 0.1, M["iron"])
    parts += spun(gear_parts(0.09, 8, 0.06, M["steel"], M["brass"], bore=False), spin(phase, 8))
    sprocket_b = spun(gear_parts(0.09, 8, 0.06, M["steel"], M["brass"], bore=False), spin(phase, 8))
    for p in sprocket_b:
        p["position"][0] += L
    parts += sprocket_b
    return [obj("chain", parts, pos=a, rot=(-90, yaw, 0))]


def _euler(rx, ry, rz):
    """Rotation matrix (rows) for the scene's XYZ Euler angles in degrees: Rz Ry Rx."""
    x, y, z = (math.radians(v) for v in (rx, ry, rz))
    Rx = [[1, 0, 0], [0, math.cos(x), -math.sin(x)], [0, math.sin(x), math.cos(x)]]
    Ry = [[math.cos(y), 0, math.sin(y)], [0, 1, 0], [-math.sin(y), 0, math.cos(y)]]
    Rz = [[math.cos(z), -math.sin(z), 0], [math.sin(z), math.cos(z), 0], [0, 0, 1]]

    def mul(A, B):
        return [[sum(A[i][k] * B[k][j] for k in range(3)) for j in range(3)] for i in range(3)]

    return mul(Rz, mul(Ry, Rx))


def _to_world(R, pos, v):
    return [pos[i] + sum(R[i][k] * v[k] for k in range(3)) for i in range(3)]


def chain_loop(phase, a, b, link=0.07, sprocket_r=0.1, paint=False, info=None):
    """A chain loop between two sprockets, built for layered animation: each
    straight run is its own object (its links only slide along the run, the two
    runs in opposite directions), the sprockets another (they turn).

    paint=True builds the runs for painting once: unshifted, with two extra
    pitches of links past each end, so the painted run can slide by up to the
    cycle's travel and still be filled when clipped back to the span between
    the sprocket centres. info (a dict) collects each run's world offset, clip
    polygon and anchor."""
    dx, dz = b[0] - a[0], b[2] - a[2]
    L = math.hypot(dx, dz)
    yaw = math.degrees(math.atan2(-dz, dx))
    n = max(2, int(L / link))
    p = L / n
    travel = phase * TEETH_PER_CYCLE * p  # the sprockets advance TEETH_PER_CYCLE teeth; the links as many pitches
    R = _euler(-90, yaw, 0)
    objs = []
    for k, side in enumerate((1, -1)):
        direction = -side  # a sprocket turning positive carries its +y side towards -x
        lo, hi = (-2 * p, L + 2 * p) if paint else (0.0, L)
        parts = []
        for i in range(int(math.floor(lo / p)) - 3, int(math.ceil(hi / p)) + 3):
            c = (i + 0.5) * p + (0.0 if paint else direction * travel)
            if lo <= c <= hi:
                parts.append(box((link * 0.85, link * 0.42, 0.05), (c, side * sprocket_r, 0), M["iron"]))
        name = f"chain_links_{k}"
        objs.append(obj(name, parts, pos=a, rot=(-90, yaw, 0)))
        if info is not None:
            u = _to_world(R, (0, 0, 0), (1, 0, 0))
            w = link * 0.3 + 0.012
            corners = [(0, side * sprocket_r - w, 0.0), (L, side * sprocket_r - w, 0.0), (L, side * sprocket_r + w, 0.0), (0, side * sprocket_r + w, 0.0)]
            info.setdefault("slide", {})[name] = {"offset": [direction * travel * c for c in u], "clip": [_to_world(R, a, c) for c in corners], "anchor": list(a)}
    sprockets = spun(gear_parts(0.09, 8, 0.06, M["steel"], M["brass"], bore=False), spin(phase, 8))
    sb = spun(gear_parts(0.09, 8, 0.06, M["steel"], M["brass"], bore=False), spin(phase, 8))
    for q in sb:
        q["position"][0] += L
    objs.append(obj("chain_sprockets", sprockets + sb, pos=a, rot=(-90, yaw, 0)))
    if info is not None:
        info.setdefault("rotors", []).append("chain_sprockets")
        ax, rf = _to_world(R, (0, 0, 0), (0, 0, 1)), _to_world(R, (0, 0, 0), (1, 0, 0))
        info.setdefault("anchors", {})["chain_sprockets"] = [{"center": list(a), "axis": ax, "ref": rf, "angle": spin(phase, 8)},
                                                             {"center": _to_world(R, a, (L, 0, 0)), "axis": ax, "ref": rf, "angle": spin(phase, 8)}]
    return objs


