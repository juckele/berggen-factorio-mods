PROPS = [_tank, _crate, _spool, _valve, _gearbox_small, _plates, _lever]


def knickknacks(colour, seed=3, region=(-0.95, 0.95, -0.9, 0.85), avoid=(), floor=0.38, step=0.24):
    """Fill the free floor with props on a jittered grid, avoiding the signature parts."""
    import random

    rng = random.Random(seed)

    class R:  # tiny numpy-free rng facade
        def uniform(self, a, b):
            return rng.uniform(a, b)

    rr = R()
    mats = [paint_mat(colour, dark=True), M["rust"], M["iron"], M["brass"], M["copper"]]
    objs = []
    x0, x1, z0, z1 = region
    k = 0
    z = z0
    while z <= z1:
        x = x0 + (step / 2 if int((z - z0) / step) % 2 else 0)
        while x <= x1:
            px, pz = x + rng.uniform(-0.05, 0.05), z + rng.uniform(-0.05, 0.05)
            if not any(a0 <= px <= a1 and b0 <= pz <= b1 for a0, a1, b0, b1 in avoid) and rng.random() < 0.85:
                fn = rng.choice(PROPS)
                parts, _ = fn(rr, rng.choice(mats))
                objs.append(obj(f"prop_{k:02d}", parts, pos=(px, floor, pz), rot=(0, rng.uniform(0, 360), 0)))
                k += 1
            x += step
        z += step
    return objs


