#!/usr/bin/env python3
"""Generate assembling machine scenes for the unicorn farts art pack.

The machines are metal: painted steel armour in the tier colour, cast iron,
brass and copper machinery. "Pastel" is the drawing medium applied later by
claude-artist's pastel style, not a colour scheme.

Every machine keeps the vanilla assembler's anatomy so a Factorio player
recognises it:
  - a 3x3 riveted steel tub with chamfered front corners on a dark plinth,
  - a raked front wall of four riveted panels with corner braces,
  - a stack of upright gears at the front-left that rises above the front
    wall and turns on a horizontal shaft (1, 2 or 3 gears by tier),
  - a valve handwheel on the left, a crank arm at the back-left,
  - (tiers 2-3) a chain running across the top-right and a motor/piston
    in the middle.
Moving parts are separate objects with a `phase` so animation frames can be
generated by re-posing them.

Two design directions:
  A  "open tub"   - close to vanilla: open-topped box full of machinery.
  B  "foundry"    - a heavy cast housing over the back half, the gear stack
                    in a front-left well, a stamping press over the work bed.

Units are tiles. x right, y up, z toward the camera (south).

    python3 build_models.py                 # all scenes
    python3 build_models.py --phase 0.25    # moving parts posed at 1/4 cycle
"""

from __future__ import annotations

